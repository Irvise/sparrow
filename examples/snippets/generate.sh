#!/usr/bin/env bash
# Writes the guides at the top of the repository from the templates here:
#
#     SNIPPETS.template.md         ->  SNIPPETS.md
#     GETTING_STARTED.template.md  ->  GETTING_STARTED.md
#
# Every piece of code they show is a real file under src/ (or templates/). Those are compiled first, with warnings
# as errors and lines of 80 columns at most (as a crate made by "alr init" checks): code that does not build
# stops the script, and the guides are left as they were. In a template, a line
#
#     @include src/greetings.ads src/greetings.adb
#
# becomes one fenced block holding those files, each headed by a comment with its name.
#
#     ./generate.sh           compile, then write the guides
#     ./generate.sh --check   compile, then fail if a guide is not what would be written (for CI)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
top="$here/../.."

(cd "$here/.." && alr -n exec -- gprbuild -q -P snippets/snippets.gpr 2>&1 | grep -v '^warn: Generating' || true;
 exit "${PIPESTATUS[0]}") || {
  echo "generate.sh: the code does not compile; nothing written" >&2
  exit 1
}

# The guide made from template $1, on standard output.
render() {
  local template="$1" line file language first
  local -a files
  echo "<!-- Generated by examples/snippets/generate.sh from examples/snippets/. Edit there, then run it. -->"
  echo
  while IFS= read -r line || [[ -n "$line" ]]; do
    if [[ "$line" != "@include "* ]]; then
      printf '%s\n' "$line"
      continue
    fi
    read -ra files <<< "${line#@include }"
    case "${files[0]}" in
      *.ads|*.adb) language=ada ;;
      *)           language=html ;;
    esac
    echo "\`\`\`$language"
    first=true
    for file in "${files[@]}"; do
      [[ -f "$here/$file" ]] || { echo "generate.sh: $file not found" >&2; exit 1; }
      $first || echo
      first=false
      if [[ $language == ada ]]; then
        echo "--  $(basename "$file")"
      else
        echo "<!-- $file -->"
      fi
      cat "$here/$file"
    done
    echo "\`\`\`"
  done < "$template"
}

status=0
for template in "$here"/*.template.md; do
  name="$(basename "$template" .template.md).md"
  if [[ "${1:-}" == "--check" ]]; then
    if ! diff -q <(render "$template") "$top/$name" > /dev/null 2>&1; then
      echo "generate.sh: $name is out of date; run examples/snippets/generate.sh" >&2
      status=1
    fi
  else
    render "$template" > "$top/$name.new"
    mv "$top/$name.new" "$top/$name"
    echo "wrote $name"
  fi
done
exit $status
